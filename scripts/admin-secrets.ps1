<#
Generates random passwords for the admin tool logins, saves them in .passwords (git-ignored)
and creates the matching Secrets in namespace raas. Safe to re-run: an existing .passwords is
reused. -Rotate generates new passwords. Run it before `kubectl apply` of k8s/infra.
#>
param (
    [switch]$Rotate
)

# Continue, not Stop: Windows PowerShell 5.1 turns native stderr into terminating errors; exit codes are checked explicitly.
$ErrorActionPreference = 'Continue'

$repoRoot = Resolve-Path "$PSScriptRoot\.."
$passFile = Join-Path $repoRoot '.passwords'

function New-Password {
    # 64 characters: 256 % 64 = 0, so the byte-to-character mapping is unbiased.
    $chars = [char[]]'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_'
    $bytes = New-Object byte[] 24
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
    -join ($bytes | ForEach-Object { $chars[$_ % 64] })
}

function Invoke-Kubectl {
    & kubectl @args
    if ($LASTEXITCODE -ne 0) { throw "kubectl $($args -join ' ') failed." }
}

$values = @{}
if ((Test-Path $passFile) -and -not $Rotate) {
    foreach ($line in Get-Content $passFile) {
        if ($line -match '^([A-Z_]+)=(.*)$') { $values[$Matches[1]] = $Matches[2] }
    }
}

# Without .passwords the old passwords are lost; do not silently replace live cluster Secrets.
if (-not (Test-Path $passFile) -and -not $Rotate) {
    kubectl -n raas get secret minio-credentials *> $null
    if ($LASTEXITCODE -eq 0) {
        throw "$passFile is missing but the cluster already has credentials. Restore the file, or pass -Rotate to replace them."
    }
}

# Keys missing from an older .passwords are added; existing ones are kept.
foreach ($key in 'MINIO_ROOT_PASSWORD', 'GRAFANA_ADMIN_PASSWORD', 'JWT_SECRET', 'RAAS_ADMIN_PASSWORD') {
    if (-not $values[$key]) { $values[$key] = New-Password }
}
if (-not $values['RAAS_ADMIN_EMAIL']) { $values['RAAS_ADMIN_EMAIL'] = 'admin@raas.local' }

Invoke-Kubectl apply -f (Join-Path $repoRoot 'k8s\infra\namespace.yaml')

# name -> literals; deployments to restart when the Secret changes (env/volumes read at pod start).
$secrets = @(
    @{ Name = 'minio-credentials'; Literals = @('MINIO_ROOT_USER=raas_minio', "MINIO_ROOT_PASSWORD=$($values['MINIO_ROOT_PASSWORD'])"); Restart = @('minio', 'media-deployment', 'loki') },
    @{ Name = 'grafana-admin'; Literals = @('GF_SECURITY_ADMIN_USER=admin', "GF_SECURITY_ADMIN_PASSWORD=$($values['GRAFANA_ADMIN_PASSWORD'])"); Restart = @('grafana') },
    @{ Name = 'user-secrets'; Literals = @("JWT_SECRET=$($values['JWT_SECRET'])", "ADMIN_EMAIL=$($values['RAAS_ADMIN_EMAIL'])", "ADMIN_PASSWORD=$($values['RAAS_ADMIN_PASSWORD'])"); Restart = @('user-deployment') }
)

foreach ($s in $secrets) {
    $before = kubectl -n raas get secret $s.Name -o 'jsonpath={.metadata.resourceVersion}' 2>$null
    $createArgs = @('-n', 'raas', 'create', 'secret', 'generic', $s.Name) + ($s.Literals | ForEach-Object { "--from-literal=$_" }) + @('--dry-run=client', '-o', 'yaml')
    $yaml = & kubectl @createArgs
    if ($LASTEXITCODE -ne 0) { throw "Building secret $($s.Name) failed." }
    $yaml | & kubectl apply -f -
    if ($LASTEXITCODE -ne 0) { throw "Applying secret $($s.Name) failed." }
    $after = kubectl -n raas get secret $s.Name -o 'jsonpath={.metadata.resourceVersion}'
    if ($before -and $before -eq $after) { continue }
    foreach ($d in $s.Restart) {
        kubectl -n raas get deployment $d *> $null
        if ($LASTEXITCODE -eq 0) { Invoke-Kubectl -n raas rollout restart deployment $d }
    }
}

# kubectl apply -k does not prune: remove what earlier versions of admin-tools created.
foreach ($svc in 'minio-console-nodeport', 'grafana-nodeport', 'redpanda-console-nodeport') {
    kubectl -n raas delete service $svc --ignore-not-found
}
kubectl -n raas delete deployment redpanda-console-auth --ignore-not-found
kubectl -n raas delete configmap redpanda-console-auth-config --ignore-not-found
kubectl -n raas delete secret redpanda-console-auth --ignore-not-found

$content = @"
# Generated by scripts/admin-secrets.ps1. Git-ignored. Do not commit, share or edit (use -Rotate to change passwords).

# RaaS admin (log in at http://localhost:30000/ to open the tools below without a second login)
RAAS_ADMIN_EMAIL=$($values['RAAS_ADMIN_EMAIL'])
RAAS_ADMIN_PASSWORD=$($values['RAAS_ADMIN_PASSWORD'])
# Signs user tokens. Rotating it logs everyone out.
JWT_SECRET=$($values['JWT_SECRET'])

# MinIO console  http://localhost:30000/admin/minio/  (still asks for this login)
MINIO_ROOT_USER=raas_minio
MINIO_ROOT_PASSWORD=$($values['MINIO_ROOT_PASSWORD'])

# Grafana  http://localhost:30000/admin/grafana/  (signed in automatically for the RaaS admin; this login is the server admin)
GRAFANA_ADMIN_USER=admin
GRAFANA_ADMIN_PASSWORD=$($values['GRAFANA_ADMIN_PASSWORD'])

# Redpanda Console  http://localhost:30000/admin/kafka/  (no login of its own; RaaS admin only)

# Adminer  http://localhost:30000/admin/adminer/  (system PostgreSQL, server postgres; Postgres credentials are not rotated)
# user raas_user, password raas_password, database raas_db
"@
Set-Content -Path $passFile -Value $content -Encoding ascii
Write-Host "Credentials written to $passFile"
